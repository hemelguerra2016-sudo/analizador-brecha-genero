CREATE TABLE organizacion (
    id_organizacion NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nit             VARCHAR2(15)  NOT NULL UNIQUE,
    razon_social    VARCHAR2(120) NOT NULL,
    ciudad          VARCHAR2(60)  NOT NULL,
    sector          VARCHAR2(60)  NOT NULL
);

CREATE TABLE area (
    id_area         NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre          VARCHAR2(60) NOT NULL,
    id_organizacion NUMBER NOT NULL,
    CONSTRAINT uq_area_org UNIQUE (nombre, id_organizacion),
    CONSTRAINT fk_area_org FOREIGN KEY (id_organizacion)
        REFERENCES organizacion (id_organizacion)
);

CREATE TABLE nivel_jerarquico (
    id_nivel NUMBER PRIMARY KEY,
    nombre   VARCHAR2(40) NOT NULL UNIQUE,
    orden    NUMBER(1)    NOT NULL UNIQUE,
    CONSTRAINT ck_nivel_orden CHECK (orden BETWEEN 1 AND 4)
);

CREATE TABLE cargo (
    id_cargo NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre   VARCHAR2(80) NOT NULL,
    id_area  NUMBER NOT NULL,
    id_nivel NUMBER NOT NULL,
    CONSTRAINT uq_cargo_area  UNIQUE (nombre, id_area),
    CONSTRAINT fk_cargo_area  FOREIGN KEY (id_area)  REFERENCES area (id_area),
    CONSTRAINT fk_cargo_nivel FOREIGN KEY (id_nivel) REFERENCES nivel_jerarquico (id_nivel)
);

CREATE TABLE empleado (
    codigo_empleado VARCHAR2(10) PRIMARY KEY,
    documento       VARCHAR2(15) NOT NULL UNIQUE,
    nombres         VARCHAR2(60) NOT NULL,
    apellidos       VARCHAR2(60) NOT NULL,
    sexo            CHAR(1)      NOT NULL,
    fecha_ingreso   DATE         NOT NULL,
    id_cargo        NUMBER       NOT NULL,
    CONSTRAINT ck_empleado_sexo  CHECK (sexo IN ('F', 'M')),
    CONSTRAINT fk_empleado_cargo FOREIGN KEY (id_cargo) REFERENCES cargo (id_cargo)
);

CREATE TABLE historial_salarial (
    id_historial    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_empleado VARCHAR2(10) NOT NULL,
    salario         NUMBER(14,2) NOT NULL,
    fecha_inicio    DATE         NOT NULL,
    fecha_fin       DATE,
    CONSTRAINT ck_salario_positivo CHECK (salario > 0),
    CONSTRAINT ck_fechas CHECK (fecha_fin IS NULL OR fecha_fin >= fecha_inicio),
    CONSTRAINT uq_hist UNIQUE (codigo_empleado, fecha_inicio),
    CONSTRAINT fk_hist_empleado FOREIGN KEY (codigo_empleado)
        REFERENCES empleado (codigo_empleado) ON DELETE CASCADE
);

-- Vista que usara la aplicacion Java para cargar las estructuras al iniciar
CREATE OR REPLACE VIEW v_salario_vigente AS
SELECT e.codigo_empleado,
       e.nombres || ' ' || e.apellidos AS nombre,
       e.sexo,
       c.nombre  AS cargo,
       a.nombre  AS area,
       n.orden   AS nivel,
       h.salario
FROM empleado e
INNER JOIN cargo c              ON c.id_cargo = e.id_cargo
INNER JOIN area a               ON a.id_area = c.id_area
INNER JOIN nivel_jerarquico n   ON n.id_nivel = c.id_nivel
INNER JOIN historial_salarial h ON h.codigo_empleado = e.codigo_empleado
WHERE h.fecha_fin IS NULL;
